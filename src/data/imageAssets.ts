/**
 * Fast deterministic string hash function
 */
export function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0; // Convert to 32bit integer
  }
  return Math.abs(hash);
}

/**
 * Deterministically pick an image from a pool based on seed (e.g. program title),
 * avoiding recently used images in the current batch if possible.
 */
export function selectFromImagePool(
  pool: string[] | undefined,
  seed: string,
  usedSet?: Set<string>
): string | null {
  if (!pool || pool.length === 0) return null;

  const baseIndex = hashString(seed) % pool.length;

  if (!usedSet || pool.length === 1) {
    const selected = pool[baseIndex];
    if (usedSet) usedSet.add(selected);
    return selected;
  }

  // Find first unused image starting from baseIndex
  for (let offset = 0; offset < pool.length; offset++) {
    const candidate = pool[(baseIndex + offset) % pool.length];
    if (!usedSet.has(candidate)) {
      usedSet.add(candidate);
      return candidate;
    }
  }

  // If all images in this pool have been used in this batch, recycle baseIndex
  const recycled = pool[baseIndex];
  usedSet.add(recycled);
  return recycled;
}
